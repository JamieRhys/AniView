import Foundation

/// Defines the standard spacing values used throughout the application.
///
/// These constants represent fixed spacing increments intended to ensure consistent layout,
/// padding, and margins across all UI components.
public enum Spacing {
    public static let zero: CGFloat         = 0
    public static let extraSmall: CGFloat   = 4
    public static let small: CGFloat        = 8
    public static let medium: CGFloat       = 16
    public static let large: CGFloat        = 24
    public static let extraLarge: CGFloat   = 32
}
